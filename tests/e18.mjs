// Avis sur l’équilibre : court et complet, générés à l’installation de la version et à chaque ajout ou suppression ; sans crédit, l’avis précédent reste.
import {start} from './server.mjs';import * as H from './h.mjs';
H.deploy();const srv=await start(8123);const b=await H.browser();
const S=H.suite('Avis sur l’équilibre');const T=S.T;
let mode='ok', n=0;
const G=o=>({json:{candidates:[{content:{parts:[{text:JSON.stringify(o)}]}}]}});
const ai=async c=>{
  if(!JSON.stringify(c.body).includes('Voici le résumé chiffré'))return G({});
  n++;
  if(mode==='quota')return {status:429,json:{error:{message:'quota'}}};
  return G({court:'Cave plutôt rouge, il lui manque des blancs. Essai '+n+'.',complet:'Détail complet '+n+'.'});
};
const r=await H.newPage(b,{ai});const page=r.page;
const errs=[];page.on('pageerror',e=>errs.push(e.message));
const ajouter=async nom=>{await page.evaluate(()=>document.querySelector('#fab').click());await H.sl(400);
  await page.evaluate(()=>document.querySelector('#sMenu [data-m=man]').click());await H.sl(450);
  await page.type('#f-name',nom);await H.sl(100);await page.click('#f-save');await H.sl(600);};
const supprimer=async nom=>{await H.tapText(page,'.tab','Ma cave');await H.sl(300);
  await page.evaluate(nom=>{const w=[...document.querySelectorAll('#list .w')].find(e=>e.textContent.includes(nom));w.querySelector('[data-a="d"]').click();},nom);
  await H.sl(400);await H.tapText(page,'#dlgB button','Supprimer');await H.sl(500);};
const attendreFin=async()=>{await H.sl(4000);for(let i=0;i<60;i++){await H.tapText(page,'.tab','Magic');await H.sl(300);if(!(await H.txt(page,'#vChiffres .bilan')).includes('mise à jour en cours'))return;await H.tapText(page,'.tab','Ma cave');await H.sl(1000);}};
const magic=async()=>{await H.tapText(page,'.tab','Magic');await H.sl(400);return H.txt(page,'#vChiffres .bilan');};

await page.goto(H.URL0);await H.sl(900);
await H.setAI(page,'gemini','AIzaTEST');
const base={src:{from:'user',to:'user'},dom:'D',color:'Rouge',region:'Margaux',grape:'Merlot',price:20,created:1,updated:1,story:'x',pairings:['a'],check:false,conf:'',sources:[],note:'',loc:'',tastings:[]};
await page.evaluate(async(base)=>{const s=await import('./store.js');
  await s.replaceAll([{...base,id:'a',name:'Vin A',year:2018,qty:2,from:2020,to:2035}]);
  await s.setMeta('bienvenue',{prenom:'Jeff',date:1});},base);
await page.reload();await H.sl(4000);
T('installation : un avis est préparé sans clic',n===1,n);
let t=await magic();
T('titre : prénom affiché',t.includes('votre cave, Jeff'));
T('avis court affiché directement',t.includes('Essai 1'),t.slice(0,200));
T('avis complet : disponible à dérouler',t.includes('Avis complet'));
T('plus de bouton « Actualiser »',!t.includes('Actualiser'));
await ajouter('Vin B');await H.tapText(page,'.tab','Ma cave');await H.sl(4000);
T('ajout d’un vin : nouvel avis',n===2,n);
t=await magic();
T('avis mis à jour après ajout',t.includes('Essai 2'));
await H.tapText(page,'.tab','Ma cave');await H.sl(4000);
T('pas de nouvel appel sans changement',n===2,n);
await supprimer('Vin B');await H.tapText(page,'.tab','Magic');await H.sl(300);await H.tapText(page,'.tab','Ma cave');await H.sl(4000);
T('suppression d’un vin : nouvel avis',n===3,n);
mode='quota';
await ajouter('Vin C');await H.tapText(page,'.tab','Ma cave');await H.sl(300);
await attendreFin();
t=await magic();
T('sans crédit : l’avis précédent reste affiché',t.includes('Essai 3')&&t.includes('mise à jour impossible'),t.slice(0,240));
const avantRechargement=n;
await page.reload();await H.sl(2500);
t=await magic();
T('après rechargement : avis conservé, sans nouvel appel',t.includes('Essai 3')&&n===avantRechargement,n+' / '+avantRechargement);
T('aucune erreur JavaScript',errs.length===0,errs.join(' | '));
await page.close();
console.log(S.out.join('\n'));await b.close();srv.close();
